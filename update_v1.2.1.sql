SET NAMES utf8mb4;

UPDATE `settings` SET `setting_value` = 'งานพัฒนาหลักสูตรและการจัดการเรียนรู้'
 WHERE `setting_key` = 'department_name' AND `setting_value` = 'งานพัฒนาหลักสูตรการเรียนการสอน';

UPDATE `settings` SET `setting_value` = 'หัวหน้างานพัฒนาหลักสูตรและการจัดการเรียนรู้'
 WHERE `setting_key` = 'approver_1_title' AND `setting_value` = 'หัวหน้างานพัฒนาหลักสูตรการเรียนการสอน';

UPDATE `users` SET `position` = 'เจ้าหน้าที่งานพัฒนาหลักสูตรและการจัดการเรียนรู้'
 WHERE `position` IN ('เจ้าหน้าที่งานพัฒนาหลักสูตรฯ', 'เจ้าหน้าที่งานพัฒนาหลักสูตรการเรียนการสอน');

UPDATE `users` SET `position` = 'หัวหน้างานพัฒนาหลักสูตรและการจัดการเรียนรู้'
 WHERE `position` IN ('หัวหน้างานพัฒนาหลักสูตรฯ', 'หัวหน้างานพัฒนาหลักสูตรการเรียนการสอน');
