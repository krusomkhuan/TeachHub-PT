-- สิ่งที่เปลี่ยน: สิทธิ์เจ้าหน้าที่ดูแลระบบ
--   - เพิ่มคอลัมน์ users.admin_permissions (JSON array ของรหัสสิทธิ์)
--     NULL = ผู้ดูแลระบบเต็มสิทธิ์ (บัญชี admin เดิมทุกบัญชียังเต็มสิทธิ์เหมือนเดิม)
--     มีค่า = เจ้าหน้าที่ดูแลระบบ ใช้ได้เฉพาะเมนูที่ผู้ดูแลระบบเต็มสิทธิ์ติ๊กให้ (หน้าแก้ไขผู้ใช้)
-- ไม่มีตารางใหม่ (ยังคงมี 38 ตาราง)
-- =====================================================================
SET NAMES utf8mb4;

ALTER TABLE `users`
  ADD COLUMN `admin_permissions` TEXT NULL DEFAULT NULL
    COMMENT 'สิทธิ์เจ้าหน้าที่ดูแลระบบ (JSON) — NULL = ผู้ดูแลระบบเต็มสิทธิ์ ใช้เฉพาะ role admin'
    AFTER `status`;
