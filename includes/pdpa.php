/**
 * ไฟล์: includes/pdpa.php
 * ข้อตกลงการคุ้มครองข้อมูลส่วนบุคคล (PDPA) ตาม พ.ร.บ.คุ้มครองข้อมูลส่วนบุคคล พ.ศ. 2562
 *   - เนื้อหาเก็บใน settings (pdpa_content) ถ้ายังไม่แก้ไขจะใช้ข้อความเริ่มต้นด้านล่าง
 *   - pdpa_version = ฉบับปัจจุบัน ผู้ใช้ที่ยังไม่ยอมรับฉบับนี้จะถูกพาไปหน้ายอมรับก่อนใช้งาน
 *
 * รูปแบบข้อความ: บรรทัดว่างคั่นย่อหน้า, "## หัวข้อ" = หัวข้อ, "- รายการ" = รายการแบบจุด
 */

/** ฉบับปัจจุบันของข้อตกลง */
function pdpa_version(): string
{
    return (string)setting('pdpa_version', '1');
}

/** บังคับให้ผู้ใช้ยอมรับก่อนใช้งานหรือไม่ */
function pdpa_required(): bool
{
    return setting('pdpa_required', '1') === '1';
}

/** ผู้ใช้คนนี้ต้องยอมรับข้อตกลง (ฉบับปัจจุบัน) ก่อนหรือไม่ */
function pdpa_needs_consent(array $user): bool
{
    return pdpa_required() && (string)($user['pdpa_version'] ?? '') !== pdpa_version();
}

/** บันทึกการยอมรับข้อตกลงฉบับปัจจุบัน */
function pdpa_accept(int $userId): void
{
    db_exec('UPDATE users SET pdpa_version = ?, pdpa_accepted_at = NOW() WHERE id = ?', 'si', [pdpa_version(), $userId]);
    log_activity('pdpa_accept', 'ยอมรับข้อตกลง PDPA ฉบับที่ ' . pdpa_version(), $userId);
}

/** วันที่ประกาศใช้ฉบับปัจจุบัน (Y-m-d) */
function pdpa_effective_date(): string
{
    return (string)setting('pdpa_updated', '');
}

/** เนื้อหาข้อตกลงปัจจุบัน */
function pdpa_content(): string
{
    return (string)setting('pdpa_content', pdpa_default_content());
}

/** ข้อความเริ่มต้นของข้อตกลง (admin แก้ไขได้ที่เมนู ข้อตกลง PDPA) */
function pdpa_default_content(): string
{
    $college = college_name();
    $unit = setting('department_name', 'งานพัฒนาหลักสูตรและการจัดการเรียนรู้');
    $sys = system_name();
    return <<<TXT
{$college} โดย{$unit} ในฐานะผู้ควบคุมข้อมูลส่วนบุคคล ให้ความสำคัญกับการคุ้มครองข้อมูลส่วนบุคคลของผู้ใช้งานระบบ {$sys} ตามพระราชบัญญัติคุ้มครองข้อมูลส่วนบุคคล พ.ศ. 2562 จึงแจ้งรายละเอียดการเก็บรวบรวม ใช้ และเปิดเผยข้อมูลส่วนบุคคล ดังนี้

## 1. ข้อมูลส่วนบุคคลที่เก็บรวบรวม
- ข้อมูลระบุตัวตน: คำนำหน้า ชื่อ นามสกุล ตำแหน่ง วิทยฐานะ แผนกวิชา รูปโปรไฟล์
- ข้อมูลการติดต่อ: อีเมล หมายเลขโทรศัพท์
- ข้อมูลบัญชีผู้ใช้: ชื่อผู้ใช้ รหัสผ่าน (เก็บแบบเข้ารหัส ไม่มีผู้ใดอ่านได้)
- ข้อมูลการปฏิบัติงาน: แผนการจัดการเรียนรู้ ข้อตกลงในการพัฒนางาน (PA) งานวิจัยในชั้นเรียน ผลการตรวจ ผลการนิเทศ และภาพถ่ายขณะนิเทศการสอน
- ข้อมูลการใช้งานระบบ: วันเวลาเข้าใช้งาน หมายเลข IP และบันทึกการใช้งาน (Log)

## 2. วัตถุประสงค์ในการใช้ข้อมูล
- ยืนยันตัวตนและควบคุมสิทธิ์การเข้าใช้งานระบบ
- รับส่ง ตรวจ และติดตามงานวิชาการของครู ตามภารกิจของสถานศึกษา
- นิเทศการสอน จัดทำรายงานผลเสนอผู้บริหาร และใช้ประกอบการพัฒนาคุณภาพการจัดการเรียนรู้
- ติดต่อสื่อสาร แจ้งข่าวสาร และกำหนดการส่งงาน
- ดูแลความปลอดภัยของระบบ และตรวจสอบย้อนหลังเมื่อเกิดปัญหา

## 3. ฐานทางกฎหมาย
สถานศึกษาประมวลผลข้อมูลเพื่อการปฏิบัติหน้าที่ในการดำเนินภารกิจเพื่อประโยชน์สาธารณะด้านการจัดการศึกษา และเพื่อประโยชน์โดยชอบด้วยกฎหมายในการบริหารงานวิชาการ ส่วนข้อมูลที่ไม่จำเป็นต่อภารกิจ เช่น รูปโปรไฟล์ จะประมวลผลตามความยินยอมของท่าน

## 4. การเปิดเผยข้อมูล
- ข้อมูลจะเปิดเผยเฉพาะผู้ที่เกี่ยวข้องตามสิทธิ์ในระบบ ได้แก่ หัวหน้าแผนกวิชา เจ้าหน้าที่งานพัฒนาหลักสูตรและการจัดการเรียนรู้ รองผู้อำนวยการ และผู้อำนวยการ
- ไม่ขาย ไม่ให้เช่า และไม่เปิดเผยแก่บุคคลภายนอก เว้นแต่มีกฎหมายกำหนด หรือหน่วยงานต้นสังกัดร้องขอตามอำนาจหน้าที่

## 5. การประเมินโดยนักเรียน นักศึกษา
การประเมินผ่าน QR Code ไม่เก็บชื่อ รหัสนักศึกษา หรือหมายเลข IP ของผู้ประเมิน ผลการประเมินจะแสดงเป็นภาพรวมเท่านั้น

## 6. ระยะเวลาการเก็บรักษา
เก็บรักษาข้อมูลตลอดระยะเวลาที่ท่านเป็นผู้ใช้งานระบบ และต่อไปไม่เกิน 5 ปีการศึกษา หรือตามระยะเวลาที่ระเบียบว่าด้วยงานสารบรรณกำหนด เมื่อพ้นกำหนดจะลบหรือทำให้ไม่สามารถระบุตัวตนได้

## 7. การรักษาความปลอดภัย
ระบบเข้ารหัสรหัสผ่าน จำกัดสิทธิ์การเข้าถึงตามบทบาท ป้องกันการเข้าถึงไฟล์โดยตรง และบันทึกการใช้งานทุกครั้ง

## 8. สิทธิของเจ้าของข้อมูล
- สิทธิขอเข้าถึงและขอรับสำเนาข้อมูลของตนเอง
- สิทธิขอแก้ไขข้อมูลให้ถูกต้อง (แก้ไขได้เองที่เมนู โปรไฟล์ของฉัน)
- สิทธิขอให้ลบ ระงับการใช้ หรือคัดค้านการประมวลผลข้อมูล
- สิทธิถอนความยินยอม โดยไม่กระทบการประมวลผลที่ได้ทำไปก่อนหน้า
- สิทธิร้องเรียนต่อสำนักงานคณะกรรมการคุ้มครองข้อมูลส่วนบุคคล

## 9. ช่องทางติดต่อ
{$unit} {$college}
TXT;
}

/** แปลงข้อความข้อตกลงเป็น HTML (escape ทุกบรรทัดก่อน) */
function pdpa_render(string $text): string
{
    $html = '';
    $inList = false;
    $para = [];
    $flush = function () use (&$html, &$para) {
        if ($para) {
            $html .= '<p>' . implode('<br>', $para) . '</p>';
            $para = [];
        }
    };
    foreach (preg_split('/\R/u', $text) as $line) {
        $line = trim($line);
        if (strpos($line, '- ') === 0) {
            $flush();
            if (!$inList) {
                $html .= '<ul>';
                $inList = true;
            }
            $html .= '<li>' . e(mb_substr($line, 2)) . '</li>';
            continue;
        }
        if ($inList) {
            $html .= '</ul>';
            $inList = false;
        }
        if ($line === '') {
            $flush();
        } elseif (strpos($line, '## ') === 0) {
            $flush();
            $html .= '<h5 class="fw-bold text-primary-th mt-4">' . e(mb_substr($line, 3)) . '</h5>';
        } else {
            $para[] = e($line);
        }
    }
    if ($inList) {
        $html .= '</ul>';
    }
    $flush();
    return $html;
}
